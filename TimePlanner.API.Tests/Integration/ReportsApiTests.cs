    private static async Task CreateTaskAsync(TestUser user, string title, string start, double duration)
    {
        var response = await user.Client.PostAsJsonAsync("/api/tasks", new { title, start, duration, categoryId = user.CategoryId });
        Assert.True(response.StatusCode == HttpStatusCode.Created, await response.Content.ReadAsStringAsync());
    }

    private static Task<HttpResponseMessage> GetAsync(TestUser user, string path, string? timeZone = null, string? origin = null)
    {
        var request = new HttpRequestMessage(HttpMethod.Get, path);
        if (timeZone is not null)
        {
            request.Headers.TryAddWithoutValidation("X-Time-Zone", timeZone);
        }

        if (origin is not null)
        {
            request.Headers.TryAddWithoutValidation("Origin", origin);
        }

        return user.Client.SendAsync(request);
    }

    private static string Header(HttpResponseMessage response, string name) =>
        response.Headers.TryGetValues(name, out var values) || response.Content.Headers.TryGetValues(name, out values)
            ? string.Join(", ", values)
            : "";

    [Fact]
    public async Task A_pdf_download_has_the_contract_headers_and_an_audit_row()
    {
        var user = await _fixture.CreateUserAsync();
        await CreateTaskAsync(user, "Deep work", "2026-10-05T08:00:00.000Z", 2);

        var response = await GetAsync(user, "/api/reports/personal.pdf?view=daily&year=2026&from=41&to=41&locale=en-US",
            "Europe/Oslo", Origin);
        var bytes = await response.Content.ReadAsByteArrayAsync();

        Assert.True(response.StatusCode == HttpStatusCode.OK, Encoding.UTF8.GetString(bytes));
        Assert.Equal("application/pdf", response.Content.Headers.ContentType?.MediaType);
        Assert.Equal(
            "attachment; filename=\"time-planner-analytics-2026-W41.pdf\"; filename*=UTF-8''time-planner-analytics-2026-W41.pdf",
            Header(response, "Content-Disposition"));
        Assert.Equal("no-store", Header(response, "Cache-Control"));
        Assert.Equal("nosniff", Header(response, "X-Content-Type-Options"));
        var documentId = Header(response, "X-Document-Id");
        Assert.True(DocumentIds.IsValid(documentId), documentId);
        Assert.StartsWith($"TP-{DateTime.UtcNow:yyyyMMdd}-", documentId);

        // The browser can only read these cross-origin because the CORS policy exposes them.
        var exposed = Header(response, "Access-Control-Expose-Headers");
        Assert.Contains("Content-Disposition", exposed);
        Assert.Contains("X-Document-Id", exposed);
        Assert.Contains("Retry-After", exposed);

        var text = ReportTestData.PdfText(bytes);
        Assert.Contains(documentId, text);
        Assert.Contains("Generated by Time Planner on", text);
        Assert.Contains("Personal report ·", text);
        Assert.Contains(user.Email, text.Replace(" ", "")); // the text extractor may split the long address
        Assert.Contains("Week 41 of 2026 (10/5/2026 – 10/11/2026)", text);
        Assert.Contains("Europe/Oslo (UTC+02:00)", text);
        Assert.Contains("Work 2 h 100%", text);

        using var scope = _fixture.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        var row = await db.ReportExports.AsNoTracking().SingleAsync(e => e.DocumentId == documentId);
        Assert.Equal(("Personal", "pdf", "daily", "Europe/Oslo", "en-US", "Letter"),
            (row.Kind, row.Format, row.ViewType, row.TimeZoneId, row.Culture, row.Paper));
        Assert.Equal(user.Id, row.RequestedByUserId);
        Assert.Equal(user.Id, row.SubjectUserId);
        Assert.Null(row.OrganizationId);
        Assert.Equal(new DateTime(2026, 10, 4, 22, 0, 0, DateTimeKind.Utc), row.RangeStartUtc);
        Assert.Equal(new DateTime(2026, 10, 11, 22, 0, 0, DateTimeKind.Utc), row.RangeEndUtc);
        Assert.Equal(SHA256.HashData(bytes), row.ContentSha256);
        Assert.InRange(row.CreatedOnUtc, DateTime.UtcNow.AddMinutes(-5), DateTime.UtcNow.AddMinutes(1));
    }

    [Fact]
    public async Task The_x_time_zone_header_decides_the_buckets()
    {
        var user = await _fixture.CreateUserAsync();
        await CreateTaskAsync(user, "Late Sunday", "2026-10-04T22:30:00.000Z", 1.5); // Monday 00:30 in Oslo
        await CreateTaskAsync(user, "Tuesday", "2026-10-06T10:00:00.000Z", 1);
        const string path = "/api/reports/personal.pdf?view=daily&year=2026&from=41&to=41&locale=en-GB&paper=A4";

        var oslo = ReportTestData.PdfText(await (await GetAsync(user, path, "Europe/Oslo")).Content.ReadAsByteArrayAsync());
        Assert.Contains("Total time 2.5 h", oslo);
        Assert.Contains("Mon 5 1.5 h", oslo);
        Assert.Contains("Europe/Oslo (UTC+02:00)", oslo);

        // No header, or one this server can't resolve: UTC.
        foreach (var zone in new[] { null, "Not/AZone" })
        {
            var utc = ReportTestData.PdfText(await (await GetAsync(user, path, zone)).Content.ReadAsByteArrayAsync());
            Assert.Contains("Total time 1 h", utc);
            Assert.Contains("Mon 5 0 h", utc);
            Assert.Contains("Time zone: UTC", utc);
        }

        // Org tasks assigned to the user count under the organization's name (same scope as the analytics page).
        var org = await OrgTestKit.CreateAsync(_fixture);
        await OrgTestKit.CreateOrgTaskAsync(org.Owner, org.OrgId, "Assigned", "2026-10-07T09:00:00.000Z", 3, org.Member);
        var csv = Encoding.UTF8.GetString(await (await GetAsync(org.Member,
            "/api/reports/personal.csv?view=weekly&year=2026&from=41&to=41&locale=en-US", "Europe/Oslo")).Content.ReadAsByteArrayAsync());
        Assert.Contains($"Category,,{org.OrgName},{org.OrgName},3.00,100.0\r\n", csv);
    }

    [Fact]
    public async Task A_csv_download_uses_the_locale_style_and_is_audited()
    {
        var user = await _fixture.CreateUserAsync();
        await CreateTaskAsync(user, "Focus", "2026-03-02T09:00:00.000Z", 1.5);

        var response = await GetAsync(user, "/api/reports/personal.csv?view=monthly&year=2026&from=0&to=11&locale=nb-NO", "Europe/Oslo");
        var bytes = await response.Content.ReadAsByteArrayAsync();

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        Assert.Equal("text/csv; charset=utf-8", response.Content.Headers.ContentType?.ToString());
        Assert.Equal(
            "attachment; filename=\"time-planner-analytics-2026-01_2026-12.csv\"; filename*=UTF-8''time-planner-analytics-2026-01_2026-12.csv",
            Header(response, "Content-Disposition"));
        Assert.Equal("no-store", Header(response, "Cache-Control"));

        Assert.Equal(new byte[] { 0xEF, 0xBB, 0xBF }, bytes[..3]);
        var lines = Encoding.UTF8.GetString(bytes, 3, bytes.Length - 3).Split("\r\n");
        var documentId = Header(response, "X-Document-Id");
        Assert.Equal("# Time Planner analytics export", lines[0]);
        Assert.Equal("# Range: januar 2026 – desember 2026", lines[1]);
        Assert.Equal("# Time zone: Europe/Oslo (UTC+01:00/+02:00)", lines[2]);
        Assert.Equal($"# Document ID: {documentId}", lines[4]);
        Assert.Equal("Section;Key;Label;Category;Hours;Share %", lines[5]);
        Assert.Equal("Summary;total_hours;Total hours;;1,50;", lines[6]);
        Assert.Contains("Period;2026-03;mars 2026;;1,50;100,0", lines);
        Assert.Contains("Period;2026-12;desember 2026;;0,00;0,0", lines);
        Assert.Contains("Template;without_template;Without template;;1,50;100,0", lines);

        using var scope = _fixture.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        var row = await db.ReportExports.AsNoTracking().SingleAsync(e => e.DocumentId == documentId);
        Assert.Equal(("csv", "monthly", "nb-NO", (string?)null), (row.Format, row.ViewType, row.Culture, row.Paper));
        Assert.Equal(SHA256.HashData(bytes), row.ContentSha256);
    }

    [Theory]
    [InlineData("view=weekly&year=2026&from=41", "to is required.")]
    [InlineData("view=yearly&year=2026&from=1&to=1", "view must be 'monthly', 'weekly' or 'daily'.")]
    [InlineData("view=weekly&year=2025&from=1&to=53", "from and to must be ISO weeks from 1 to 52 of 2025.")]
    [InlineData("view=monthly&year=2026&from=0&to=12", "For the monthly view, from and to are month indexes from 0 (January) to 11 (December).")]
    [InlineData("view=weekly&year=2026&from=41&to=38", "from must not be after to.")]
    [InlineData("view=daily&year=2026&from=40&to=41", "For the daily view, from and to must be the same week.")]
    [InlineData("view=weekly&year=2026&from=1&to=1&paper=B5", "paper must be 'A4' or 'Letter'.")]
    public async Task Invalid_selections_are_400_with_message_and_errors(string query, string error)
    {
        var user = await _fixture.CreateUserAsync();

        var response = await GetAsync(user, $"/api/reports/personal.pdf?{query}");

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal("application/json", response.Content.Headers.ContentType?.MediaType);
        using var body = JsonDocument.Parse(await response.Content.ReadAsStringAsync());
        Assert.Contains(error, body.RootElement.GetProperty("message").GetString());
        Assert.Contains(body.RootElement.GetProperty("errors").EnumerateArray(), e => e.GetString() == error);
    }

