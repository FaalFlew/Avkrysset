    [Fact]
    public async Task More_than_10_reports_a_minute_are_429_with_retry_after()
    {
        var user = await _fixture.CreateUserAsync();
        const string path = "/api/reports/personal.csv?view=weekly&year=2026&from=1&to=1";

        for (var i = 0; i < 10; i++)
        {
            Assert.Equal(HttpStatusCode.OK, (await GetAsync(user, path)).StatusCode);
        }

        var limited = await GetAsync(user, path, origin: Origin);
        Assert.Equal(HttpStatusCode.TooManyRequests, limited.StatusCode);
        var retryAfter = int.Parse(Header(limited, "Retry-After"));
        Assert.InRange(retryAfter, 1, 60);
        Assert.Contains("Retry-After", Header(limited, "Access-Control-Expose-Headers"));
        using (var body = JsonDocument.Parse(await limited.Content.ReadAsStringAsync()))
        {
            Assert.Equal($"Too many report requests. Please try again in {retryAfter} second{(retryAfter == 1 ? "" : "s")}.",
                body.RootElement.GetProperty("message").GetString());
            Assert.Empty(body.RootElement.GetProperty("errors").EnumerateArray());
        }

        // Per user: somebody else is not affected, and other endpoints are not limited.
        var other = await _fixture.CreateUserAsync();
        Assert.Equal(HttpStatusCode.OK, (await GetAsync(other, path)).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await user.Client.GetAsync("/api/users/me")).StatusCode);

        using var scope = _fixture.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        Assert.Equal(10, await db.ReportExports.CountAsync(e => e.RequestedByUserId == user.Id));
        _output.WriteLine($"Retry-After: {retryAfter}");
    }
