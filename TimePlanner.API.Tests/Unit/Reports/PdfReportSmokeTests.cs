        Assert.Contains("Analytics report", text);
        Assert.Contains("Personal report · Ada Lovelace", text);
        Assert.Contains("Week 40 of 2026 (9/28/2026 – 10/4/2026)", text);
        Assert.Contains("Europe/Oslo (UTC+02:00)", text);
        Assert.Contains("Total time 8 h", text);
        Assert.Contains("Mon 28 2.5 h", text);
        Assert.Contains("Work 7 h 88%", text);
        Assert.Contains("Gym 1 h 12%", text);
        Assert.Contains("Standup Work 1.5 h 19%", text);
        Assert.Contains("Without template 6.5 h 81%", text);
        Assert.Contains("Page 1 of 2", text);
        Assert.Contains("Tasks Time Duration Title Category Template Created by", text);
        Assert.Equal("Time Planner", document.Information.Creator);
    }

