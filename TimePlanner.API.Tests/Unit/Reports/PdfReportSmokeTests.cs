using System.Text;
using Microsoft.Extensions.Logging.Abstractions;
using TimePlanner.API.Features.Queries.Tasks;
using TimePlanner.API.Features.Reports;
using UglyToad.PdfPig;
using UglyToad.PdfPig.Content;
using Xunit.Abstractions;
using static TimePlanner.API.Tests.Unit.Reports.ReportTestData;

namespace TimePlanner.API.Tests.Unit.Reports;

/// <summary>
/// Renders real PDFs with QuestPDF and reads them back with PdfPig. Also run in a 32-bit process to prove the
/// win-x86 engine the Azure App Service needs works:
/// <c>dotnet test TimePlanner.API.Tests --arch x86 --filter "FullyQualifiedName~PdfReportSmokeTests"</c>.
/// </summary>
public sealed class PdfReportSmokeTests
{
    private const double A4Width = 595.28;
    private const double LetterWidth = 612;

    private readonly ITestOutputHelper _output;
    private readonly PdfReportRenderer _renderer = new(NullLogger<PdfReportRenderer>.Instance);

    public PdfReportSmokeTests(ITestOutputHelper output) => _output = output;

    private static readonly AnalyticsTaskRow[] Week40 =
    {
        Row("2026-09-28T08:00:00Z", 2.5),
        Row("2026-09-29T08:00:00Z", 1.5, template: Standup),
        Row("2026-09-30T17:00:00Z", 1, Gym, "Gym", "#0E9C8C"),
        Row("2026-10-02T08:00:00Z", 3)
    };

    private static readonly Dictionary<Guid, AnalyticsTemplate> StandupTemplate = new()
    {
        [Standup] = new AnalyticsTemplate("Standup", "Work", "#2F7FE0")
    };

    private byte[] Render(ReportModel model, string dumpName)
    {
        var pdf = _renderer.RenderPdf(model);
        Dump(dumpName, pdf);
        Assert.Equal("%PDF-", Encoding.ASCII.GetString(pdf, 0, 5));
        return pdf;
    }

    [Fact]
    public void A_weekly_report_has_the_header_kpis_tables_and_footer()
    {
        var model = Build(Request(TaskAnalyticsBreakdown.Daily, 2026, 40, 40, "Europe/Oslo", "en-US"), Week40, StandupTemplate);

        var pdf = Render(model, "weekly-en-US.pdf");
        var text = PdfText(pdf);
        _output.WriteLine(text);

        using var document = PdfDocument.Open(pdf);
        Assert.Equal(1, document.NumberOfPages);
        Assert.Equal(LetterWidth, document.GetPage(1).Width, 0.5); // en-US => Letter

        Assert.Contains(DocumentId, text);
        Assert.Contains("Generated by Time Planner on 2026-10-05 08:00 UTC", text);
        Assert.Contains("Analytics report", text);
        Assert.Contains("Personal report · Ada Lovelace", text);
        Assert.Contains("Week 40 of 2026 (9/28/2026 – 10/4/2026)", text);
        Assert.Contains("Europe/Oslo (UTC+02:00)", text);
        Assert.Contains("Total time 8 h", text);
        Assert.Contains("Mon 28 2.5 h", text);
        Assert.Contains("Work 7 h 88%", text);
        Assert.Contains("Gym 1 h 12%", text);
        Assert.Contains("Standup Work 1.5 h 19%", text);
        Assert.Contains("Without template 6.5 h 81%", text);
        Assert.Contains("Page 1 of 1", text);
        Assert.Equal("Time Planner", document.Information.Creator);
    }

    [Fact]
    public void A4_and_letter_have_the_right_page_width()
    {
        var a4 = Render(ReportWarmUp.SampleModel(locale: "nb-NO"), "sample-nb-NO.pdf");
        var letter = Render(ReportWarmUp.SampleModel(locale: "nb-NO", paper: PaperSize.Letter), "sample-letter.pdf");

        using (var document = PdfDocument.Open(a4))
        {
            Assert.Equal(A4Width, document.GetPage(1).Width, 0.5);
            Assert.Equal(841.89, document.GetPage(1).Height, 0.5);
        }

        using (var document = PdfDocument.Open(letter))
        {
            Assert.Equal(LetterWidth, document.GetPage(1).Width, 0.5);
            Assert.Equal(792, document.GetPage(1).Height, 0.5);
        }

        // nb-NO formatting: decimal comma, Norwegian dates.
        var text = PdfText(a4);
        Assert.Contains("7,5 h", text);
        Assert.Contains("28.09.2026", text);
    }

    [Fact]
    public void A_year_by_month_and_a_year_by_week_render()
    {
        var tasks = Enumerable.Range(0, 365).Select(day => Row("2026-01-01T09:00:00Z", 1 + day % 3)).ToList();
        for (var i = 0; i < tasks.Count; i++)
        {
            tasks[i] = tasks[i] with { Start = tasks[i].Start.AddDays(i) };
        }

        var months = PdfText(Render(Build(Request(TaskAnalyticsBreakdown.Monthly, 2026, 0, 11, "Europe/Oslo", "en-GB"), tasks), "year-months.pdf"));
        Assert.Contains("January 2026 – December 2026", months);
        Assert.Contains("Europe/Oslo (UTC+01:00/+02:00)", months);
        Assert.Contains("Jan", months);
        Assert.Contains("Dec", months);

        var weeks = PdfText(Render(Build(Request(TaskAnalyticsBreakdown.Weekly, 2026, 1, 53, "UTC", "en-GB"), tasks), "year-weeks.pdf"));
        Assert.Contains("Weeks 1–53 of 2026", weeks);
        // 53 bars: axis labels are thinned to every 5th week.
        Assert.Contains("W1 ", weeks);
        Assert.Contains("W26", weeks);
        Assert.Contains("W51", weeks);
        Assert.DoesNotContain("W2 ", weeks);
    }

    [Fact]
    public void Long_tables_continue_on_more_pages()
    {
        var tasks = Enumerable.Range(0, 90)
            .Select(i => Row("2026-09-28T08:00:00Z", 0.25 + i % 5, Guid.NewGuid(), $"Category {i:D2}", "#5E6AD2"))
            .ToList();

        var pdf = Render(Build(Request(TaskAnalyticsBreakdown.Daily, 2026, 40, 40, locale: "en-GB"), tasks), "many-categories.pdf");

        using var document = PdfDocument.Open(pdf);
        Assert.True(document.NumberOfPages >= 2, $"{document.NumberOfPages} pages");
        var text = PdfText(pdf);
        Assert.Contains($"Page 2 of {document.NumberOfPages}", text);
        Assert.Contains("Category 00", text);
        Assert.Contains("Category 89", text);
        Assert.All(document.GetPages(), page => Assert.Contains(DocumentId, page.Text));
    }

    [Fact]
    public void An_empty_range_says_so()
    {
        var text = PdfText(Render(Build(Request(TaskAnalyticsBreakdown.Weekly, 2026, 1, 4), Array.Empty<AnalyticsTaskRow>()), "empty.pdf"));

        Assert.Contains("No tasks in this period.", text);
        Assert.Contains("Total time 0 h", text);
        Assert.DoesNotContain("Time by category", text);
    }

    /// <summary>
    /// Right-to-left scripts are reordered and Arabic is shaped (contextual letter forms), CJK and emoji have glyphs.
    /// PDF text comes out in visual order, so RTL words are read back reversed.
    /// </summary>
    [Fact]
    public void Arabic_hebrew_cjk_and_emoji_names_render_shaped_and_right_to_left()
    {
        var tasks = new[]
        {
            Row("2026-09-28T08:00:00Z", 3, Guid.NewGuid(), "العمل اليومي", "#2F7FE0"),
            Row("2026-09-29T08:00:00Z", 2, Guid.NewGuid(), "עבודה שוטפת", "#DA6A1C"),
            Row("2026-09-30T08:00:00Z", 1, Guid.NewGuid(), "工作 仕事 업무", "#8E55CC"),
            Row("2026-10-01T08:00:00Z", 1, Guid.NewGuid(), "Running 🏃", "#B87D10"),
            Row("2026-10-02T08:00:00Z", 1, Guid.NewGuid(), "Ελληνικά Русский", "#D3449E"),
            Row("2026-10-03T08:00:00Z", 1.5, Guid.NewGuid(), "Reading", "#0E9C8C", template: Standup)
        };
        var templates = new Dictionary<Guid, AnalyticsTemplate> { [Standup] = new("قراءة كتاب", "Reading", "#0E9C8C") };

        var pdf = Render(Build(Request(TaskAnalyticsBreakdown.Daily, 2026, 40, 40, "Asia/Dubai", "ar-EG", subject: "مريم"), tasks, templates), "scripts-ar-EG.pdf");

        using var document = PdfDocument.Open(pdf);
        var page = document.GetPage(1);
        var words = page.GetWords().ToList();
        var visual = string.Join(" ", words.Select(w => w.Text));
        var normalized = visual.Normalize(NormalizationForm.FormKC);
        _output.WriteLine(visual);

        // Copy/search: every glyph maps back to text (Noto Sans Arabic UI draws letters and their dots as one glyph).
        Assert.DoesNotContain(page.Letters, l => l.Value.Contains((char)0));
        var reading = Assert.Single(words, w => Reverse(Logical(w)) == "قراءة");
        Assert.Contains(words, w => Reverse(Logical(w)) == "مريم");

        // The Arabic template name sits on the same baseline as the numbers in its table row.
        var rowNumbers = page.Letters
            .Where(l => char.IsAsciiDigit(l.Value[0]) && Math.Abs(l.StartBaseLine.Y - reading.Letters[0].StartBaseLine.Y) < 6)
            .ToList();
        Assert.NotEmpty(rowNumbers);
        Assert.All(rowNumbers, l => Assert.Equal(reading.Letters[0].StartBaseLine.Y, l.StartBaseLine.Y, 0.75));

        // Arabic: contextual (initial/medial/final) presentation forms prove shaping; NFKC maps them back to letters.
        // Read left to right, an RTL word is its logical text reversed (its first letter is drawn rightmost).
        var arabicWord = words.First(w => Reverse(Logical(w)) == "العمل"); // in the top-category tile and the table
        Assert.Contains(arabicWord.Letters, l => l.Value.Any(c => c is >= '\uFB50' and <= '\uFDFF' or >= '\uFE70' and <= '\uFEFF'));

        // Hebrew: no shaping, but letters and words run right to left (the first word is the one on the right).
        var avoda = Assert.Single(words, w => Reverse(Logical(w)) == "עבודה");
        var shotefet = Assert.Single(words, w => Reverse(Logical(w)) == "שוטפת");
        Assert.True(avoda.BoundingBox.Left > shotefet.BoundingBox.Left);

        // Control: left-to-right text is not reversed.
        Assert.Contains(words, w => Logical(w) == "Running");

        // CJK (the font maps 工 to the Kangxi radical too, which NFKC folds back), Korean, emoji, Greek and Cyrillic.
        Assert.Contains("工作", normalized);
        Assert.Contains("仕事", normalized);
        Assert.Contains("업무", normalized);
        Assert.Contains("🏃", visual);
        Assert.Contains("Ελληνικά", visual);
        Assert.Contains("Русский", visual);

        Assert.Contains("Asia/Dubai (UTC+04:00)", PdfText(pdf));
    }

    [Fact]
    public void Characters_without_a_glyph_render_blank_instead_of_failing()
    {
        var tasks = new[] { Row("2026-09-28T08:00:00Z", 1, Guid.NewGuid(), "ภาษาไทย Thai", "#2F7FE0") };

        var text = PdfText(Render(Build(Request(TaskAnalyticsBreakdown.Daily, 2026, 40, 40, locale: "th-TH"), tasks), "thai.pdf"));

        Assert.Contains("Thai", text);
        Assert.Contains(DocumentId, text);
    }

    // A word's letters in drawing order, folded with NFKC (presentation forms -> letters), without unmapped glyphs.
    private static string Logical(Word word) =>
        string.Concat(word.Letters.Select(l => l.Value)).Normalize(NormalizationForm.FormKC).Replace("\0", "");

    private static string Reverse(string text) => new(text.Reverse().ToArray());
}
